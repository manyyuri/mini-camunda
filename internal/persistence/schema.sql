-- mini-camunda schema（镜像 Camunda 7.19 ACT_ 表，列名保持原名）
-- 对应 camunda-engine-7.19.0 org.camunda.bpm.engine.impl.db.*.create.*.sql

-- ===== General =====
CREATE TABLE IF NOT EXISTS ACT_GE_PROPERTY (
  NAME_  TEXT PRIMARY KEY,
  VALUE_ TEXT
);

-- ===== Repository =====
CREATE TABLE IF NOT EXISTS ACT_GE_BYTEARRAY (
  ID_           TEXT PRIMARY KEY,
  NAME_         TEXT,
  DEPLOYMENT_ID_ TEXT,
  BYTES_        BLOB
);
CREATE TABLE IF NOT EXISTS ACT_RE_DEPLOYMENT (
  ID_           TEXT PRIMARY KEY,
  NAME_         TEXT,
  DEPLOY_TIME_  TEXT
);
CREATE TABLE IF NOT EXISTS ACT_RE_PROCDEF (
  ID_                   TEXT PRIMARY KEY,
  KEY_                  TEXT NOT NULL,
  VERSION_              INTEGER NOT NULL,
  DEPLOYMENT_ID_        TEXT NOT NULL,
  RESOURCE_NAME_        TEXT NOT NULL,
  HAS_START_FORM_KEY_   INTEGER DEFAULT 0
);
CREATE INDEX IF NOT EXISTS IDX_PROCDEF_KEY ON ACT_RE_PROCDEF (KEY_);

-- ===== Runtime =====
CREATE TABLE IF NOT EXISTS ACT_RU_EXECUTION (
  ID_            TEXT PRIMARY KEY,
  REV_           INTEGER NOT NULL DEFAULT 1,
  PROC_INST_ID_  TEXT NOT NULL,
  BUSINESS_KEY_  TEXT,
  PROC_DEF_ID_   TEXT NOT NULL,
  ACT_ID_        TEXT,
  ACT_INST_ID_   TEXT,
  PARENT_ID_     TEXT,
  SUPER_EXEC_    TEXT,
  SCOPE_ACTIVITY_ TEXT,   -- mini 扩展：作用域执行对应的活动 id（Camunda 内存推导，无此列）
  IS_ACTIVE_     INTEGER NOT NULL DEFAULT 1,
  IS_CONCURRENT_ INTEGER NOT NULL DEFAULT 0,
  IS_SCOPE_      INTEGER NOT NULL DEFAULT 0,
  IS_EVENT_SCOPE_ INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS IDX_EXEC_INST ON ACT_RU_EXECUTION (PROC_INST_ID_);
CREATE INDEX IF NOT EXISTS IDX_EXEC_PARENT ON ACT_RU_EXECUTION (PARENT_ID_);

CREATE TABLE IF NOT EXISTS ACT_RU_VARIABLE (
  ID_            TEXT PRIMARY KEY,
  REV_           INTEGER NOT NULL DEFAULT 1,
  TYPE_          TEXT NOT NULL,
  NAME_          TEXT NOT NULL,
  PROC_INST_ID_  TEXT NOT NULL,
  EXECUTION_ID_  TEXT,
  TASK_ID_       TEXT,
  BYTEARRAY_ID_  TEXT,
  DOUBLE_        REAL,
  LONG_          INTEGER,
  TEXT_          TEXT,
  TEXT2_         TEXT,
  IS_LOCAL_      INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS IDX_VAR_INST ON ACT_RU_VARIABLE (PROC_INST_ID_, NAME_);

CREATE TABLE IF NOT EXISTS ACT_RU_TASK (
  ID_           TEXT PRIMARY KEY,
  REV_          INTEGER NOT NULL DEFAULT 1,
  NAME_         TEXT,
  ASSIGNEE_     TEXT,
  CREATED_      TEXT,
  PRIORITY_     INTEGER DEFAULT 50,
  DUE_DATE_     TEXT,
  PROC_DEF_ID_  TEXT,
  PROC_INST_ID_ TEXT,
  EXECUTION_ID_ TEXT,
  TASK_DEF_KEY_ TEXT
);
CREATE INDEX IF NOT EXISTS IDX_TASK_INST ON ACT_RU_TASK (PROC_INST_ID_);

CREATE TABLE IF NOT EXISTS ACT_RU_IDENTITYLINK (
  ID_       TEXT PRIMARY KEY,
  TYPE_     TEXT,
  USER_ID_  TEXT,
  GROUP_ID_ TEXT,
  TASK_ID_  TEXT,
  PROC_DEF_ID_ TEXT
);

CREATE TABLE IF NOT EXISTS ACT_RU_JOBDEF (
  ID_               TEXT PRIMARY KEY,
  PROC_DEF_ID_      TEXT,
  PROC_DEF_KEY_     TEXT,
  ACT_ID_           TEXT,
  JOB_TYPE_         TEXT,
  JOB_CONFIGURATION_ TEXT
);

CREATE TABLE IF NOT EXISTS ACT_RU_JOB (
  ID_                 TEXT PRIMARY KEY,
  REV_                INTEGER NOT NULL DEFAULT 1,
  TYPE_               TEXT NOT NULL,          -- message | timer
  LOCK_OWNER_         TEXT,
  LOCK_EXP_TIME_      TEXT,
  EXCLUSIVE_          INTEGER NOT NULL DEFAULT 1,
  EXECUTION_ID_       TEXT,
  PROCESS_INSTANCE_ID_ TEXT,
  PROC_DEF_ID_        TEXT,
  RETRIES_            INTEGER NOT NULL DEFAULT 3,
  DUEDATE_            TEXT,
  HANDLER_TYPE_       TEXT NOT NULL,
  HANDLER_CFG_        TEXT,
  EXCEPTION_MSG_      TEXT,
  JOB_DEF_ID_         TEXT
);
CREATE INDEX IF NOT EXISTS IDX_JOB_INST ON ACT_RU_JOB (PROCESS_INSTANCE_ID_);

CREATE TABLE IF NOT EXISTS ACT_RU_EVENT_SUBSCR (
  ID_            TEXT PRIMARY KEY,
  REV_           INTEGER NOT NULL DEFAULT 1,
  EVENT_TYPE_    TEXT NOT NULL,   -- message | signal
  EVENT_NAME_    TEXT NOT NULL,
  EXECUTION_ID_  TEXT,
  PROC_INST_ID_  TEXT,
  ACTIVITY_ID_   TEXT,
  CONFIGURATION_ TEXT
);
CREATE INDEX IF NOT EXISTS IDX_SUBSCR_NAME ON ACT_RU_EVENT_SUBSCR (EVENT_NAME_);

CREATE TABLE IF NOT EXISTS ACT_RU_EXT_TASK (
  ID_            TEXT PRIMARY KEY,
  REV_           INTEGER NOT NULL DEFAULT 1,
  TOPIC_NAME_    TEXT NOT NULL,
  WORKER_ID_     TEXT,
  LOCK_EXP_TIME_ TEXT,
  RETRIES_       INTEGER NOT NULL DEFAULT 3,
  ERROR_MESSAGE_ TEXT,
  EXECUTION_ID_  TEXT,
  PROC_INST_ID_  TEXT,
  PROC_DEF_ID_   TEXT,
  ACT_ID_        TEXT
);

CREATE TABLE IF NOT EXISTS ACT_RU_INCIDENT (
  ID_                 TEXT PRIMARY KEY,
  INCIDENT_TYPE_      TEXT NOT NULL,  -- failedJob | failedExternalTask
  INCIDENT_MSG_       TEXT,
  INCIDENT_TIMESTAMP_ TEXT,
  EXECUTION_ID_       TEXT,
  ACTIVITY_ID_        TEXT,
  PROC_INST_ID_       TEXT,
  PROC_DEF_ID_        TEXT,
  CAUSE_INCIDENT_ID_  TEXT,
  JOB_ID_             TEXT
);

-- ===== History =====
CREATE TABLE IF NOT EXISTS ACT_HI_PROCINST (
  ID_              TEXT PRIMARY KEY,   -- = PROC_INST_ID_
  BUSINESS_KEY_    TEXT,
  PROC_DEF_KEY_    TEXT,
  PROC_DEF_ID_     TEXT,
  START_TIME_      TEXT,
  END_TIME_        TEXT,
  END_ACT_ID_      TEXT,
  DELETE_REASON_   TEXT,
  STATE_           TEXT
);

CREATE TABLE IF NOT EXISTS ACT_HI_ACTINST (
  ID_                  TEXT PRIMARY KEY,
  PARENT_ACT_INST_ID_  TEXT,
  PROC_DEF_KEY_        TEXT,
  PROC_DEF_ID_         TEXT,
  PROC_INST_ID_        TEXT,
  EXECUTION_ID_        TEXT,
  ACT_ID_              TEXT,
  ACT_NAME_            TEXT,
  ACT_TYPE_            TEXT,
  ASSIGNEE_            TEXT,
  START_TIME_          TEXT,
  END_TIME_            TEXT,
  DURATION_            INTEGER,
  ACT_INST_STATE_      TEXT
);
CREATE INDEX IF NOT EXISTS IDX_HI_ACT_INST ON ACT_HI_ACTINST (PROC_INST_ID_);

CREATE TABLE IF NOT EXISTS ACT_HI_TASKINST (
  ID_             TEXT PRIMARY KEY,   -- = TASK_ID_
  PROC_DEF_KEY_   TEXT,
  PROC_DEF_ID_    TEXT,
  PROC_INST_ID_   TEXT,
  EXECUTION_ID_   TEXT,
  ACT_INST_ID_    TEXT,
  NAME_           TEXT,
  ASSIGNEE_       TEXT,
  START_TIME_     TEXT,
  END_TIME_       TEXT,
  DURATION_       INTEGER,
  TASK_DEF_KEY_   TEXT,
  DELETE_REASON_  TEXT
);

CREATE TABLE IF NOT EXISTS ACT_HI_VARINST (
  ID_                  TEXT PRIMARY KEY,
  PROC_INST_ID_        TEXT,
  EXECUTION_ID_        TEXT,
  TASK_ID_             TEXT,
  NAME_                TEXT,
  VAR_TYPE_            TEXT,
  TEXT_                TEXT,
  LONG_                INTEGER,
  DOUBLE_              REAL,
  STATE_               TEXT,   -- created | updated | deleted
  CREATE_TIME_         TEXT,
  LAST_UPDATED_TIME_   TEXT
);

CREATE TABLE IF NOT EXISTS ACT_HI_JOBLOG (
  ID_                  TEXT PRIMARY KEY,
  TIMESTAMP_           TEXT,
  JOB_ID_              TEXT,
  JOB_DUE_DATE_        TEXT,
  JOB_RETRIES_         INTEGER,
  JOB_EXCEPTION_MSG_   TEXT,
  JOB_DEF_ID_          TEXT,
  STATE_               TEXT   -- created | succeeded | failed | deleted
);

CREATE TABLE IF NOT EXISTS ACT_HI_INCIDENT (
  ID_                  TEXT PRIMARY KEY,   -- = INCIDENT_ID_
  CREATE_TIME_         TEXT,
  END_TIME_            TEXT,
  INCIDENT_TYPE_       TEXT,
  INCIDENT_MSG_        TEXT,
  EXECUTION_ID_        TEXT,
  ACTIVITY_ID_         TEXT,
  PROC_INST_ID_        TEXT,
  CAUSE_INCIDENT_ID_   TEXT
);
